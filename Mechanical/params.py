def _overlap_xz(a, b):
    """a, b = (cx, cz, w, h). True если прямоугольники пересекаются."""
    ax, az, aw, ah = a
    bx, bz, bw, bh = b
    ox = (ax + aw / 2.0) > (bx - bw / 2.0) and (bx + bw / 2.0) > (ax - aw / 2.0)
    oz = (az + ah / 2.0) > (bz - bh / 2.0) and (bz + bh / 2.0) > (az - ah / 2.0)
    return ox and oz


def sanity_check():
    errs = []
    x0, x1 = 0.0, CASE_W          # внутренний проём панели (стенки 3 мм)
    z0, z1 = 0.0, CASE_H

    def _check(items, what):
        for name, cx, cz, w, h in items:
            if not (cx - w / 2.0 >= x0 - 1e-9 and cx + w / 2.0 <= x1 + 1e-9):
                errs.append("%s: выход по X за %s (%.2f..%.2f, рамка %.2f..%.2f)"
                            % (name, what, cx - w / 2.0, cx + w / 2.0, x0, x1))
            if not (cz - h / 2.0 >= z0 - 1e-9 and cz + h / 2.0 <= z1 + 1e-9):
                errs.append("%s: выход по Z за %s (%.2f..%.2f, рамка %.2f..%.2f)"
                            % (name, what, cz - h / 2.0, cz + h / 2.0, z0, z1))
        for i in range(len(items)):
            for j in range(i + 1, len(items)):
                ni, cxi, czi, wi, hi = items[i]
                nj, cxj, czj, wj, hj = items[j]
                if _overlap_xz((cxi, czi, wi, hi), (cxj, czj, wj, hj)):
                    errs.append("перекрытие (%s): %s <-> %s" % (what, ni, nj))

    _check(_front_items(), "панель")
    _check(_back_items(), "крышка")

    return errs


if __name__ == "__main__":
    problems = sanity_check()
    if problems:
        print("!!! SANITY: обнаружены проблемы раскладки:")
        for p in problems:
            print("   -", p)
    else:
        print("SANITY OK: габарит %.1f x %.1f x %.1f, раскладка валидна"
              % (CASE_W, CASE_D, CASE_H))
        for name, cx, cz, w, h in _front_items():
            print("   %-12s X %6.2f..%6.2f  Z %6.2f..%6.2f"
                  % (name, cx - w / 2, cx + w / 2, cz - h / 2, cz + h / 2))
